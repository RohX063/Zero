#ifndef ZERO_EVALUATION_THREATS_H
#define ZERO_EVALUATION_THREATS_H

#include "../bitboard.h"
#include "../types.h"

class Position;

namespace Zero::Evaluation {

// Static tactical-pressure summary for one side. This is intentionally an
// evaluation-side model: the Search::Worker/Stack remains responsible for
// proving concrete tactics through the move tree.
struct ThreatFeatures {
    int attackedPieces = 0;
    int hangingPieces = 0;
    int loosePieces = 0;
    int multiAttackedPieces = 0;
    int pawnThreats = 0;
    int forks = 0;
    int highValueForks = 0;
    int pins = 0;
    int xrayTargets = 0;
    int skewers = 0;
    int promotionThreats = 0;
    int score = 0;
};

// Analyze static tactical pressure generated by one side.
ThreatFeatures analyzeThreats(const Position& position, Color color);

// Threat evaluation from White's point of view.
int evaluateThreats(const Position& position);

} // namespace Zero::Evaluation

#endif
